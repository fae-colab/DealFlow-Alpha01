const assert=require('node:assert/strict');
const O=require('./outcomes.js');
const legacy={version:'1.3',actions:[],outcomes:[{id:'A1',status:'completed',actualCommission:12500,minutes:45,at:'2026-11-01T10:00:00Z',updatedAt:'2026-11-01T11:00:00Z'}]};
const migrated=O.migrateState(legacy);
assert.equal(migrated.outcomeEvents.length,1);
assert.equal(migrated.outcomeEvents[0].eventId,'legacy-outcome:A1');
assert.equal(migrated.outcomeEvents[0].recordedBy,'legacy_migration');
assert.deepEqual(migrated.outcomes[0],{id:'A1',status:'completed',actualCommission:12500,minutes:45,at:'2026-11-01T10:00:00Z',updatedAt:'2026-11-01T11:00:00Z',eventId:'legacy-outcome:A1',notes:'Migrated from the Alpha 01.3 mutable outcome record.'});
const original=JSON.parse(JSON.stringify(migrated.outcomeEvents[0]));
const first=O.appendOutcomeEvent(migrated.outcomeEvents,{actionId:'A1',status:'completed',actualCommission:12500,minutes:45,recordedAt:'2026-11-02T10:00:00Z',occurredAt:'2026-11-02T09:00:00Z',notes:'Initial confirmed record'});
assert.equal(first.length,2);
assert.equal(first[1].eventType,'outcome_corrected');
assert.equal(first[1].supersedesEventId,'legacy-outcome:A1');
assert.deepEqual(first[0],original,'prior event remains unchanged');
const corrected=O.appendOutcomeEvent(first,{actionId:'A1',status:'completed',actualCommission:13200,minutes:50,recordedAt:'2026-11-03T10:00:00Z',notes:'Commission receipt corrected against statement'});
assert.equal(corrected.length,3);
assert.equal(corrected[2].supersedesEventId,first[1].eventId);
assert.equal(O.currentEvents(corrected).length,1);
assert.equal(O.projectOutcomes(corrected)[0].actualCommission,13200);
assert.equal(O.projectOutcomes(corrected)[0].minutes,50);
assert.deepEqual(corrected.slice(0,2),first,'correction appends; it does not mutate earlier events');
assert.equal(O.validateOutcomeEvents(corrected).length,0);
assert.throws(()=>O.appendOutcomeEvent(corrected,{actionId:'A1',status:'completed',actualCommission:-1,minutes:2}),/actualCommission/);
assert.ok(O.validateOutcomeEvents([{...corrected[0],eventId:'bad',eventType:'outcome_corrected',supersedesEventId:'missing'}]).length);
assert.ok(O.validateOutcomeEvents([corrected[0],{...corrected[1],eventId:'fork',supersedesEventId:corrected[0].eventId}]).length);
const reloaded=O.migrateState({actions:[],outcomes:[],outcomeEvents:corrected});
assert.deepEqual(reloaded.outcomeEvents,corrected,'event log survives reload migration');
assert.equal(reloaded.outcomes[0].actualCommission,13200);
console.log('Append-only outcome event tests passed.');
